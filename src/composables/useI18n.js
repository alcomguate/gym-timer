export function useI18n() {
  const { language } = storeToRefs(useSettingsStore())
  function t(key, ...args) {
    const val = dict[language.value]?.[key] ?? dict.es[key] ?? key
    return typeof val === 'function' ? val(...args) : val
  }
  return { t, language }
}
